-- Tự tạo dòng profiles khi có user mới trong auth.users (đăng ký qua form hoặc
-- admin tạo tay trong Dashboard đều kích hoạt). security definer để bỏ qua RLS
-- của chính bảng profiles khi insert.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, department, employee_code, role)
  values (
    new.id,
    new.email,
    new.raw_user_meta_data ->> 'full_name',
    new.raw_user_meta_data ->> 'department',
    new.raw_user_meta_data ->> 'employee_code',
    case upper(new.raw_user_meta_data ->> 'department')
      when 'RD' then 'rd'
      when 'QA' then 'qa'
      when 'QC' then 'qc'
      when 'KH' then 'kh'
      else 'qc'
    end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

