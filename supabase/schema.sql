create table if not exists products (
  ma_sp text primary key,
  ten_sp text,
  pool text not null check (pool in ('subtilis', 'clausii-loai1', 'clausii-loai2')),
  thanh_phan text,
  ham_luong numeric,
  tube_ml numeric,
  so_ong_nhip numeric,
  ncv text,
  -- SP 2 thành phần hoạt chất (vd Co-biozin): pool2/ham_luong2 là chủng + mật độ
  -- đích của thành phần thứ 2, pha CHUNG 1 tank với thành phần chính (pool/ham_luong).
  -- Để trống (null) = SP chỉ có 1 thành phần.
  pool2 text check (pool2 in ('subtilis', 'clausii-loai1', 'clausii-loai2')),
  ham_luong2 numeric,
  thanh_phan2 text,
  -- Chấp nhận dùng loại NL còn lại làm dự phòng khi loại chính (pool/pool2) không đủ, vd
  -- Progermila ưu tiên loại 1 nhưng vẫn dùng được loại 2; Co-biozin ưu tiên loại 2 nhưng vẫn
  -- dùng được loại 1. Mặc định false = chỉ dùng đúng loại đã khai báo.
  allow_other_loai boolean not null default false,
  -- Thứ tự hiển thị tuỳ chỉnh (admin kéo thả trong tab Sản phẩm); null = xếp theo ma_sp.
  sort_order integer
);

