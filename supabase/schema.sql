-- Cho user tự cập nhật CỘT EMAIL hiển thị (profiles.email) của CHÍNH MÌNH qua 1 hàm RPC hẹp —
-- không mở rộng policy update trực tiếp trên bảng để tránh user tự nâng quyền role/status.
create or replace function public.update_own_profile_email(new_email text)
returns void
language plpgsql
security definer set search_path = public
as $$
begin
  update public.profiles set email = new_email where id = auth.uid();
end;
$$;
grant execute on function public.update_own_profile_email(text) to authenticated;

-- VIEW admin xem nhanh trong Table Editor (schema public, không cần đổi sang schema "auth")
-- gồm cả password đã băm — REVOKE khỏi anon/authenticated để không lộ qua REST API công khai.
create or replace view public.user_accounts_admin_view as
select
  p.id, p.full_name, p.phone, p.email, u.encrypted_password,
  p.role, p.status, p.department, p.employee_code, p.created_at
from public.profiles p
join auth.users u on u.id = p.id;
revoke all on public.user_accounts_admin_view from anon, authenticated;

